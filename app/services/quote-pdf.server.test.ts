import { describe, it, expect } from "vitest";
import { cleanDecimal, renderQuotePdfBytes, type QuotePdfData } from "./quote-pdf.server";

const base: QuotePdfData = {
  quoteRef: "abcd1234",
  createdAt: new Date("2026-08-01T00:00:00Z"),
  validUntil: new Date("2026-08-15T00:00:00Z"),
  companyName: "Acme Wholesale",
  buyerEmail: "buyer@acme.example",
  poReference: "PO-77",
  currencyCode: "USD",
  lines: [
    { title: "Stoneware Mug", sku: "MUG-12", quantity: 10, price: "9.50" },
    { title: "Matching Lid", sku: "LID-12", quantity: 10, price: "5.00" },
  ],
  totals: null,
  totalsMoment: "sent",
  brand: { name: "Acme Wholesale", primaryColor: "#4F46E5" },
  whiteLabel: false,
  locale: null,
};

function toStr(b: Uint8Array) { return Buffer.from(b).toString("latin1"); }

describe("renderQuotePdfBytes (pure)", () => {
  it("produces a valid branded PDF with the quote content", () => {
    const s = toStr(renderQuotePdfBytes(base));
    expect(s.startsWith("%PDF-1.4")).toBe(true);
    expect(s.trimEnd().endsWith("%%EOF")).toBe(true);
    expect(s).toContain("(QUOTE) Tj");
    expect(s).toContain("(#abcd1234) Tj");
    expect(s).toContain("(Stoneware Mug) Tj");
    expect(s).toContain("(USD 9.50) Tj"); // the unit price as typed
    expect(s).toContain("Generated by Mannon");
  });

  it("white-label removes the Mannon footer", () => {
    const s = toStr(renderQuotePdfBytes({ ...base, whiteLabel: true }));
    expect(s).not.toContain("Generated by Mannon");
  });

  it("renders a second locale (fr) labels", () => {
    const s = toStr(renderQuotePdfBytes({ ...base, locale: "fr-CA" }));
    expect(s).toContain("(DEVIS) Tj");
    expect(s).toContain("(Prix unitaire) Tj");
    expect(s).toContain("Généré par Mannon");
  });

  it("caps rows and notes the overflow", () => {
    const many = Array.from({ length: 40 }, (_, i) => ({ title: `Item ${i}`, sku: null, quantity: 1, price: "1.00" }));
    const s = toStr(renderQuotePdfBytes({ ...base, lines: many }));
    expect(s).toContain("more item"); // "…and 12 more item(s)"
  });

  it("with no saved Shopify calculation, shows no total at all", () => {
    const s = toStr(renderQuotePdfBytes(base));
    expect(s).toContain("(Totals are calculated by Shopify when the quote is sent.) Tj");
    expect(s).not.toMatch(/\((Subtotal|Total|Estimated subtotal)\) Tj/);
  });

  it("shows Shopify's saved totals as returned, with when they were calculated", () => {
    const s = toStr(
      renderQuotePdfBytes({
        ...base,
        totals: { subtotal: "130.50", totalTax: "13.05", total: "158.55", currencyCode: "USD", totalDiscounts: "14.50", totalShipping: "15.00", calculatedAt: "2026-11-20T09:00:00.000Z" },
      }),
    );
    for (const row of ["(Subtotal) Tj", "(USD 130.50) Tj", "(Discount) Tj", "(USD -14.50) Tj", "(Shipping) Tj", "(USD 15.00) Tj", "(Tax) Tj", "(USD 13.05) Tj", "(Total) Tj", "(USD 158.55) Tj"]) {
      expect(s).toContain(row);
    }
    expect(s).toContain("(Totals calculated by Shopify on 2026-11-20.) Tj");
  });

  it("never shows a number Shopify didn't return or the merchant didn't type", () => {
    const data: QuotePdfData = {
      ...base,
      poReference: null,
      lines: [
        { title: "Mug", sku: null, quantity: 24, price: "9.50" }, // 24 × 9.50 would be 228.00
        { title: "Setup fee", sku: null, quantity: 3, price: "50.00" }, // 3 × 50 would be 150.00
      ],
      totals: { subtotal: "250.20", totalTax: "25.02", total: "290.22", currencyCode: "USD", totalDiscounts: "27.80", totalShipping: "15.00" },
    };
    const s = toStr(renderQuotePdfBytes(data));
    const shown = [...s.matchAll(/\(USD (-?\d+\.\d+)\) Tj/g)].map((m) => m[1].replace(/^-/, ""));
    const allowed = new Set(["9.50", "50.00", "250.20", "25.02", "290.22", "27.80", "15.00"]);
    expect(shown.length).toBe(7);
    for (const n of shown) expect(allowed.has(n)).toBe(true);
    expect(s).not.toContain("228.00");
    expect(s).not.toContain("378.00"); // the lines added up
    expect(s).toContain("(Totals calculated by Shopify when the quote was sent.) Tj");
  });

  it("prints stored prices without arithmetic", () => {
    expect([cleanDecimal("9.5000"), cleanDecimal("12"), cleanDecimal("0.1250")]).toEqual(["9.50", "12.00", "0.125"]);
  });
});
