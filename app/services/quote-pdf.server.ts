/**
 * F25.1 — branded quote PDF (server-side, dependency-free). Guardrail #1: the
 * PDF shows only what the merchant typed (quantity, unit price) and the totals
 * Shopify returned from the last draftOrderCalculate saved on the quote, with
 * when they were calculated. It never adds, multiplies or estimates anything;
 * with no saved calculation it shows no total. Branding comes from F20;
 * white-label removes the Mannon footer. Localized labels render a second
 * locale. The layout is a pure function so it's unit-testable without a DB.
 */

export interface QuotePdfLine {
  title: string;
  sku: string | null;
  quantity: number;
  /** Agreed unit price, exactly as stored (a decimal string). */
  price: string;
}

/** Shopify's saved totals (Quote.totalsSnapshot), shown as Shopify wrote them. */
export interface QuotePdfTotals {
  subtotal: string;
  totalTax: string;
  total: string;
  currencyCode: string;
  totalDiscounts?: string;
  totalShipping?: string;
  /** When Shopify calculated them (ISO), if recorded. */
  calculatedAt?: string;
}

export interface QuotePdfData {
  quoteRef: string; // short, non-sensitive
  createdAt: Date;
  validUntil: Date | null;
  companyName: string;
  buyerEmail: string;
  poReference: string | null;
  currencyCode: string;
  lines: QuotePdfLine[];
  /** Null when Shopify hasn't calculated this quote yet. */
  totals: QuotePdfTotals | null;
  /** For a saved calculation without a date: when it happened in the quote's life. */
  totalsMoment: "sent" | "ordered";
  brand: { name: string; primaryColor: string | null };
  whiteLabel: boolean;
  locale?: string | null;
}

